"""ADK version of the "Create New Bank Account" agentic workflow.

Mirrors the no-code tutorial
https://developer.ibm.com/learningpaths/get-started-watsonx-orchestrate/create-agentic-workflows-no-code/

Passport (flow input, uploaded in the chat) -> extract details -> branch on nationality
  - Spain: form (pre-filled from the passport) -> generative prompt -> confirmation message
  - other: "please visit a branch" message
"""

from pydantic import BaseModel, Field

from ibm_watsonx_orchestrate.flow_builder.data_map import DataMap
from ibm_watsonx_orchestrate.flow_builder.flows import END, START, Branch, Flow, flow
from ibm_watsonx_orchestrate.flow_builder.types import (
    Assignment,
    DocExtConfigField,
    DocumentProcessingCommonInput,
)

PROMPT_LLM = "watsonx/ibm/granite-4-h-small"
# Values the extractor may return for a Spanish passport (it often keeps the native-language label, e.g. ESPAÑOLA).
SPANISH_NATIONALITIES = [
    "spain",
    "spanish",
    "españa",
    "espana",
    "española",
    "espanola",
    "esp",
]
NOT_SUPPORTED_MESSAGE = (
    "Sorry, online account opening is currently available only for Spanish nationals. "
    "Please visit one of our branches to open your account."
)


class AccountRequestOutput(BaseModel):
    confirmation_message: str = Field(
        default="", description="Message shown to the user at the end of the workflow."
    )


class PassportFields(BaseModel):
    """Fields extracted from the passport by the document extractor.

    Plain string fields with guidance in the description only: on SaaS, the same fields with
    type="date", examples or example_value made the docext node fail.
    """

    passport_number: DocExtConfigField = Field(
        default=DocExtConfigField(
            name="Passport number",
            field_name="passport_number",
            description="The passport number, usually printed at the top right of the data page.",
        )
    )
    nationality: DocExtConfigField = Field(
        default=DocExtConfigField(
            name="Nationality",
            field_name="nationality",
            description=(
                "Find the value in the field labeled Nationality and return the corresponding country name in "
                "English, for example Portuguese gives Portugal, Polish gives Poland, Spanish or Española gives Spain."
            ),
        )
    )
    given_name: DocExtConfigField = Field(
        default=DocExtConfigField(
            name="Given name",
            field_name="given_name",
            description="The given name(s) of the holder.",
        )
    )
    surname: DocExtConfigField = Field(
        default=DocExtConfigField(
            name="Surname",
            field_name="surname",
            description="The surname(s) of the holder.",
        )
    )
    date_of_birth: DocExtConfigField = Field(
        default=DocExtConfigField(
            name="Date of birth",
            field_name="date_of_birth",
            description=(
                "The holder's date of birth. The label may be multilingual (e.g. 'Date of birth', "
                "'Fecha de nacimiento', 'Date de naissance'). Never use the date of issue or the date "
                "of expiry. Return it as DD MMM YYYY, for example 08 AUG 1988."
            ),
        )
    )


class PrivateVars(BaseModel):
    confirmation_message: str = Field(
        default="", description="Confirmation message generated by the prompt node."
    )


class ConfirmationInput(BaseModel):
    first_name: str = Field(description="Customer first name")
    last_name: str = Field(description="Customer last name")
    account_type: str = Field(description="Requested account type (Current or Saving)")
    phone_number: str = Field(description="Customer contact phone number")


class ConfirmationOutput(BaseModel):
    message: str = Field(description="The confirmation message for the customer")


def _value(expression: str, target: str = "self.input.default") -> DataMap:
    data_map = DataMap()
    data_map.add(Assignment(target_variable=target, value_expression=expression))
    return data_map


@flow(
    name="create_new_bank_account_agentic_workflow",
    display_name="Create New Bank Account Agentic Workflow",
    description=(
        "Creates a request to open a new bank account. The user is asked to upload a picture of their passport."
    ),
    # The passport is the workflow input: the chat asks the user to upload it, then docext reads flow.input.document_ref.
    input_schema=DocumentProcessingCommonInput,
    output_schema=AccountRequestOutput,
    private_schema=PrivateVars,
)
def build_create_new_bank_account_agentic_workflow(aflow: Flow) -> Flow:
    # 1. Extract Passport Details (document extractor) from the uploaded passport
    extract, _ = aflow.docext(
        name="extract_passport_details",
        display_name="Extract Passport Details",
        description="Extracts the holder's details from a passport image.",
        fields=PassportFields(),
    )
    extract.map_input(
        input_variable="document_ref", expression="flow.input.document_ref"
    )

    # 2a. Other nationalities: stop with a message (also returned as the flow output)
    not_supported = aflow.userflow(
        name="not_supported",
        display_name="Other nationalities",
        label="Account opening",
    )
    not_supported_msg = not_supported.activity(
        name="not_supported_message", display_name="not_supported_message"
    )
    not_supported_msg.message_output_field(
        name="not_supported_message", text=NOT_SUPPORTED_MESSAGE
    )
    not_supported.sequence(START, not_supported_msg, END)
    store_not_supported = aflow.script(
        name="store_not_supported",
        display_name="Store Not Supported",
        script=f"flow.private.confirmation_message = {NOT_SUPPORTED_MESSAGE!r}",
    )

    # 2b. Spain: Account Creation Request form, pre-filled from the passport
    passport = 'flow["extract_passport_details"].output'
    request = aflow.userflow(
        name="account_creation_request",
        display_name="Account Creation Request",
        label="Account Creation Request",
    )
    form = request.form(
        name="account_details",
        display_name="Account Details",
        instructions="Check the details extracted from your passport and complete the form.",
    )
    form.text_input_field(
        name="first_name",
        label="First Name",
        required=True,
        default=_value(f"{passport}.given_name"),
    )
    form.text_input_field(
        name="last_name",
        label="Last Name",
        required=True,
        default=_value(f"{passport}.surname"),
    )
    form.text_input_field(
        name="nationality",
        label="Nationality",
        required=True,
        default=_value(f"{passport}.nationality"),
    )
    form.text_input_field(
        name="passport_number",
        label="Passport Number",
        required=True,
        default=_value(f"{passport}.passport_number"),
    )
    form.text_input_field(
        name="date_of_birth",
        label="Date of Birth",
        required=True,
        default=_value(f"{passport}.date_of_birth"),
    )
    form.text_input_field(
        name="phone_number", label="Contact Phone Number", required=True
    )
    form.number_input_field(
        name="annual_income", label="Annual Income", required=True, is_integer=False
    )
    form.single_choice_input_field(
        name="account_type",
        label="Account Type",
        required=True,
        show_as_dropdown=False,
        choices=_value('["Current", "Saving"]', target="self.input.choices"),
    )
    request.sequence(START, form, END)

    # 3. Generative prompt: confirmation message
    confirmation = aflow.prompt(
        name="generate_confirmation",
        display_name="Generate Confirmation",
        llm=PROMPT_LLM,
        system_prompt="You are a friendly bank assistant who writes short, professional confirmation messages.",
        user_prompt=[
            "Write a short confirmation message for a new bank account request.",
            "Customer: {first_name} {last_name}",
            "Account type: {account_type}",
            "Phone number: {phone_number}",
            "The message must include: a personal greeting, a statement that the request was successfully "
            "submitted, a reference number, a note that an agent will call the customer at the phone number "
            "provided, and a sign-off from the bank.",
        ],
        input_schema=ConfirmationInput,
        output_schema=ConfirmationOutput,
    )
    details = 'flow["account_creation_request"]["account_details"].output'
    confirmation.map_input(
        input_variable="first_name", expression=f"{details}.first_name"
    )
    confirmation.map_input(
        input_variable="last_name", expression=f"{details}.last_name"
    )
    confirmation.map_input(
        input_variable="account_type", expression=f"{details}.account_type"
    )
    confirmation.map_input(
        input_variable="phone_number", expression=f"{details}.phone_number"
    )

    # 4. Display the confirmation to the user (message text can only reference flow.input / flow.private)
    store = aflow.script(
        name="store_confirmation",
        display_name="Store Confirmation",
        script="flow.private.confirmation_message = flow.nodes['generate_confirmation'].output.message",
    )
    show = aflow.userflow(
        name="show_confirmation",
        display_name="Confirmation",
        label="Account Creation Request",
    )
    show_msg = show.activity(
        name="confirmation_message", display_name="confirmation_message"
    )
    show_msg.message_output_field(
        name="confirmation_message", text="{flow.private.confirmation_message}"
    )
    show.sequence(START, show_msg, END)

    # Wiring
    nationality: Branch = aflow.conditions(
        name="nationality_check", display_name="Nationality?"
    )
    nationality.condition(
        expression=f"str({passport}.nationality).strip().lower() in {SPANISH_NATIONALITIES}",
        to_node=request,
    ).condition(to_node=not_supported, default=True)

    aflow.sequence(START, extract, nationality)
    aflow.sequence(request, confirmation, store, show, END)
    aflow.sequence(not_supported, store_not_supported, END)

    aflow.map_output(
        output_variable="confirmation_message",
        expression="flow.private.confirmation_message",
        default_value="",
    )
    return aflow
